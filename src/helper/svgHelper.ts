/** Create an inline-flex span element from an SVG string. */
function svgNode(str: string): HTMLElement {
  const el = document.createElement("span");
  el.style.display = "inline-flex";
  el.style.alignItems = "center";
  el.innerHTML = str;
  return el;
}

